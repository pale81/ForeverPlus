# Builds Data/Instances.lua (instances of the client's group finder) from the
# game table GroupFinderActivity as CSV, e.g. the "CSV" download on
# wago.tools/db2 for the client build. The world map only shows entrances of
# instances listed here.
# Usage: python3 tools/instances.py GroupFinderActivity.csv BUILD
import csv, os, sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATEGORIES = {2: 'dungeon', 114: 'raid'}  # GroupFinderCategory: dungeons, raids


def main(path, build):
    kinds = defaultdict(set)
    with open(path, newline='', encoding='utf-8-sig') as f:
        for row in csv.DictReader(f):
            kind = CATEGORIES.get(int(row['GroupFinderCategoryID']))
            if kind and int(row['MapID']) > 0:
                kinds[int(row['MapID'])].add(kind)

    out = ['-- Generated by tools/instances.py from GroupFinderActivity, build %s.' % build,
           '-- Instance map ID -> "dungeon" (also as a raid) or "raid" (raid only).',
           'local _, ns = ...', '',
           'ns.InstanceBuild = "%s"' % build,
           'ns.Instances = {']
    for map_id in sorted(kinds):
        out.append('\t[%d] = "%s",' % (map_id, 'dungeon' if 'dungeon' in kinds[map_id] else 'raid'))
    out.append('}')
    with open(os.path.join(ROOT, 'Data', 'Instances.lua'), 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('%d instances' % len(kinds))


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit('Usage: python3 tools/instances.py GroupFinderActivity.csv BUILD')
    main(*sys.argv[1:])
