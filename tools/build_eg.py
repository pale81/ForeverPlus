# Builds Data/Inns.lua (innkeepers with their position) and Data/RadarEG.lua
# (vendors of recipes with their position) from the open data of Efficient
# Games (CC BY 4.0, https://github.com/JIVESCORP/eg-link-output-wowf):
# the NPCs that offered "Make this inn your home" (gossip icon 132052) and the
# vendors whose stock holds recipes, over all recorded builds.
# Usage: python3 tools/build_eg.py <checkout of eg-link-output-wowf>
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BINDER_ICON = 132052
RECIPE_NAME = re.compile(r'^(Recipe|Pattern|Plans|Schematic|Formula|Manual|Design|Technique|Book):')
MAX_VENDOR_MAPS = 3


def main(checkout):
    base = os.path.join(checkout, 'data', 'wow_classic_beta')
    found = {}
    builds = sorted(os.listdir(base))
    for build in builds:
        path = os.path.join(base, build, 'npcs.json')
        if not os.path.exists(path):
            continue
        with open(path, encoding='utf-8') as f:
            data = json.load(f)
        for npc, row in data.get('npcs', {}).items():
            options = row.get('options') or {}
            if not any(o.get('icon') == BINDER_ICON for o in options.values()):
                continue
            positions = [p for p in row.get('positions', []) if p.get('uiMap') and p.get('mapX') and p.get('mapY')]
            if not positions:
                continue
            side = row.get('side')
            found[int(npc)] = (positions[0]['uiMap'], positions[0]['mapX'] * 100, positions[0]['mapY'] * 100,
                               'A' if side == 'Alliance' else 'H' if side == 'Horde' else 'N', row.get('name') or '?')
    lines = [
        '-- Generated by tools/build_eg.py from the open data of Efficient Games',
        '-- (https://github.com/JIVESCORP/eg-link-output-wowf, CC BY 4.0, builds %s to %s):' % (builds[0], builds[-1]),
        '-- NPCs that offered "Make this inn your home". Players\' own finds (Modules/Innkeepers.lua) are added at run time.',
        '-- { npc ID, map ID, x, y (percent of the map), team (A, H, N), name }',
        'local _, ns = ...',
        '',
        'ns.InnData = {',
    ]
    for npc in sorted(found):
        uimap, x, y, team, name = found[npc]
        lines.append('\t{ %d, %d, %.1f, %.1f, "%s", %s },' % (npc, uimap, x, y, team, json.dumps(name, ensure_ascii=False)))
    lines += ['}', '']
    with open(os.path.join(ROOT, 'Data', 'Inns.lua'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print('%d innkeepers' % len(found))
    build_radar(base, builds)


def build_radar(base, builds):
    npcs, stock = {}, {}
    for build in builds:
        path = os.path.join(base, build, 'npcs.json')
        if os.path.exists(path):
            with open(path, encoding='utf-8') as f:
                for npc, row in json.load(f).get('npcs', {}).items():
                    npcs[int(npc)] = row
        path = os.path.join(base, build, 'vendors.json')
        if os.path.exists(path):
            with open(path, encoding='utf-8') as f:
                for npc, row in json.load(f).get('vendors', {}).items():
                    entry = stock.setdefault(int(npc), {'name': row.get('name'), 'positions': [], 'items': set()})
                    entry['positions'] = row.get('positions') or entry['positions']
                    for item in (row.get('entries') or {}).values():
                        if RECIPE_NAME.match(item.get('name') or ''):
                            entry['items'].add(item['itemId'])
    lines = [
        '-- Generated by tools/build_eg.py from the open data of Efficient Games',
        '-- (https://github.com/JIVESCORP/eg-link-output-wowf, CC BY 4.0): vendors whose stock holds recipes.',
        '-- Added to ns.RadarData (Data/Radar.lua): new vendors, and recipes the vendors there lack.',
        '-- { npc ID, name, team (A, H, N), map ID, x, y, { recipe item, ... } }',
        'local _, ns = ...',
        '',
        'local data = ns.RadarData',
        'local more = {',
    ]
    count = 0
    for npc in sorted(stock):
        entry = stock[npc]
        positions = [p for p in entry['positions'] if p.get('uiMap') and p.get('mapX') and p.get('mapY')]
        maps = {p['uiMap'] for p in positions}
        if not entry['items'] or not positions or len(maps) > MAX_VENDOR_MAPS:
            continue
        side = (npcs.get(npc) or {}).get('side')
        team = 'A' if side == 'Alliance' else 'H' if side == 'Horde' else 'N'
        position = positions[0]
        lines.append('\t{ %d, %s, "%s", %d, %.1f, %.1f, { %s } },' % (
            npc, json.dumps(entry['name'] or '?', ensure_ascii=False), team, position['uiMap'],
            position['mapX'] * 100, position['mapY'] * 100, ', '.join(str(i) for i in sorted(entry['items']))))
        count += 1
    lines += [
        '}',
        'if data then',
        '\tfor _, row in ipairs(more) do',
        '\t\tlocal known = data.vendors[row[1]]',
        '\t\tif known then',
        '\t\t\tlocal listed = {}',
        '\t\t\tfor _, item in ipairs(known[5]) do listed[item] = true end',
        '\t\t\tfor _, item in ipairs(row[7]) do',
        '\t\t\t\tif not listed[item] then known[5][#known[5] + 1] = item end',
        '\t\t\tend',
        '\t\telse',
        '\t\t\tdata.vendors[row[1]] = { row[2], false, row[3], { { row[4], row[5], row[6] } }, row[7] }',
        '\t\tend',
        '\tend',
        'end',
        '',
    ]
    with open(os.path.join(ROOT, 'Data', 'RadarEG.lua'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print('%d recipe vendors' % count)


if __name__ == '__main__':
    main(sys.argv[1])
