# Builds Data/MapOverlays.lua (all world map parts per map art) from the
# game tables WorldMapOverlay and WorldMapOverlayTile as CSV, e.g. the
# "CSV" downloads on wago.tools/db2 for the client build.
# Usage: python3 tools/mapoverlays.py WorldMapOverlay.csv WorldMapOverlayTile.csv BUILD
import csv, math, os, sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TILE = 256  # tile size of the classic map art layers (C_Map.GetMapArtLayers)


def rows(path):
    with open(path, newline='', encoding='utf-8-sig') as f:
        return list(csv.DictReader(f))


def main(overlay_path, tile_path, build):
    tiles = defaultdict(list)
    for t in rows(tile_path):
        if int(t['LayerIndex']) == 0:
            tiles[int(t['WorldMapOverlayID'])].append((int(t['RowIndex']), int(t['ColIndex']), int(t['FileDataID'])))

    arts = defaultdict(list)
    flags, conditions, skipped = Counter(), 0, []
    for o in sorted(rows(overlay_path), key=lambda o: int(o['ID'])):
        oid, width, height = int(o['ID']), int(o['TextureWidth']), int(o['TextureHeight'])
        grid = sorted(tiles.get(oid, []))
        columns, count = math.ceil(width / TILE), math.ceil(width / TILE) * math.ceil(height / TILE)
        # Row-major and complete, as the map draws them (file index = row * columns + column).
        if not grid or [(r, c) for r, c, _ in grid] != [(i // columns, i % columns) for i in range(count)]:
            skipped.append(oid)
            continue
        flags[int(o['Flags'])] += 1
        if int(o['PlayerConditionID']) != 0:
            conditions += 1
        numbers = [width, height, int(o['OffsetX']), int(o['OffsetY'])] + [f for _, _, f in grid]
        arts[int(o['UiMapArtID'])].append(','.join(map(str, numbers)))

    out = ['-- Generated by tools/mapoverlays.py from WorldMapOverlay and WorldMapOverlayTile, build %s.' % build,
           '-- Map art ID -> "width,height,left,top,file,file,…;…" (tile files row by row).',
           'local _, ns = ...', '',
           'ns.MapOverlayBuild = "%s"' % build,
           'ns.MapOverlays = {']
    for art in sorted(arts):
        out.append('\t[%d] = "%s",' % (art, ';'.join(arts[art])))
    out.append('}')
    os.makedirs(os.path.join(ROOT, 'Data'), exist_ok=True)
    with open(os.path.join(ROOT, 'Data', 'MapOverlays.lua'), 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')

    total = sum(len(v) for v in arts.values())
    print('%d map arts, %d parts; skipped (no or incomplete tiles): %s' % (len(arts), total, skipped or '-'))
    print('Flags: %s; with player condition: %d' % (dict(flags), conditions))


if __name__ == '__main__':
    if len(sys.argv) != 4:
        sys.exit('Usage: python3 tools/mapoverlays.py WorldMapOverlay.csv WorldMapOverlayTile.csv BUILD')
    main(*sys.argv[1:])
