# Builds Data/Places.lua (towns and capital cities with their world position)
# from the game tables AreaPOI and AreaTable as CSV, e.g. the "CSV"
# downloads on wago.tools/db2 for the client build. Towns are the points of
# interest flagged like Goldshire or Razor Hill, capitals like Stormwind; the
# area ID gives the name in the client's language at runtime.
# Usage: python3 tools/places.py AreaPOI.csv AreaTable.csv BUILD
import csv, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOWN_FLAGS = (1, 5)
CAPITAL_FLAGS = 29


def rows(path):
    with open(path, newline='', encoding='utf-8-sig') as f:
        return list(csv.DictReader(f))


def area_index(areas):
    index = {}
    for a in areas:
        index.setdefault((a['AreaName_lang'].lower(), a['ContinentID']), int(a['ID']))
    return index


def find_area(index, name, continent):
    candidates = [name, name + ' City']
    if name.startswith('The '):
        candidates.append(name[4:])
    for candidate in candidates:
        area = index.get((candidate.lower(), continent))
        if area:
            return area
    return 0


def main(poi_path, area_path, build):
    index = area_index(rows(area_path))
    places, unmatched = [], []
    for p in rows(poi_path):
        flags = int(p['Flags'])
        if int(p['PlayerConditionID']) != 0 or int(p['WorldStateID']) != 0:
            continue
        if flags == CAPITAL_FLAGS:
            kind = 'city'
        elif flags in TOWN_FLAGS and p['Icon'] in ('4', '6'):
            kind = 'town'
        else:
            continue
        area = find_area(index, p['Name_lang'], p['ContinentID'])
        if not area:
            unmatched.append(p['Name_lang'])
        places.append((int(p['ContinentID']), float(p['Pos_0']), float(p['Pos_1']), area, p['Name_lang'], kind))

    out = ['-- Generated by tools/places.py from AreaPOI and AreaTable, build %s.' % build,
           '-- { continent, world x, world y, area ID (0: none), name, "city"|"town" }',
           'local _, ns = ...', '',
           'ns.PlaceBuild = "%s"' % build,
           'ns.Places = {']
    for c, x, y, area, name, kind in places:
        out.append('\t{ %d, %.1f, %.1f, %d, "%s", "%s" },' % (c, x, y, area, name.replace('"', '\\"'), kind))
    out.append('}')
    with open(os.path.join(ROOT, 'Data', 'Places.lua'), 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('%d places (%d cities); without area: %s' % (len(places), sum(1 for p in places if p[5] == 'city'), unmatched or '-'))


if __name__ == '__main__':
    if len(sys.argv) != 4:
        sys.exit('Usage: python3 tools/places.py AreaPOI.csv AreaTable.csv BUILD')
    main(*sys.argv[1:])
