"""Builds Data/FontFamilies.lua from the font definitions of the game's interface code (Blizzard_Fonts_Shared,
GameFonts.xml and friends): which font file and height each alphabet (roman, korean, chinese, russian) of a font
family uses, and which font object inherits which family.

The Fonts module needs it: a font object set again with Font:SetFont keeps one file only and loses the files of the
other alphabets (Korean, Chinese and Russian names turned into boxes). With these members it builds a new family
(CreateFontFamily) with the chosen face for the roman alphabet and the game's files for the others.

    python3 -I tools/build_fonts.py <wow-ui-source checkout>
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The game's load order (Blizzard_Fonts_Shared.toc, family Mainline, in the game).
FILES = ["Mainline/Fonts.xml", "Shared/Fonts.xml", "Shared/GameFonts.xml", "Mainline/GameFonts.xml",
         "Shared/FontStyles.xml", "Mainline/FontStyles.xml", "Mainline/GameFontStyles.xml", "Shared/GameFontStyles.xml"]

ATTR = re.compile(r'(\w+)="([^"]*)"')


def attrs(text):
    return dict(ATTR.findall(text))


def main(checkout):
    base = os.path.join(checkout, "Interface", "AddOns", "Blizzard_Fonts_Shared")
    families, fonts = {}, {}
    for name in FILES:
        path = os.path.join(base, name)
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8", errors="ignore") as f:
            text = f.read()
        for match in re.finditer(r'<FontFamily\s([^>]*)>(.*?)</FontFamily>', text, re.S):
            family = attrs(match.group(1)).get("name")
            members = {}
            for member in re.finditer(r'<Member alphabet="(\w+)">\s*<Font\s([^>]*?)/?>', match.group(2)):
                info = attrs(member.group(2))
                if info.get("font") and info.get("height"):
                    members[member.group(1)] = (info["font"], float(info["height"]))
            if family and "roman" in members:
                families[family] = members
        for match in re.finditer(r'<Font\s([^>]*?)/?>', text):
            info = attrs(match.group(1))
            if info.get("name"):
                fonts[info["name"]] = info

    def family_of(name, depth=0):
        if name in families:
            return name
        info = fonts.get(name)
        if not info or depth > 20 or info.get("font"):
            return None  # an own file: no family
        parent = info.get("inherits")
        return family_of(parent.split(",")[0].strip(), depth + 1) if parent else None

    inherits = {}
    for name in sorted(fonts):
        family = family_of(name)
        if family and family != name:
            inherits[name] = family

    lines = [
        "-- Generated by tools/build_fonts.py from the font definitions of the game's interface code (Blizzard_Fonts_Shared).",
        "-- families[name] = { [alphabet] = { file, height } }; inherits[font object] = the family it uses.",
        "local _, ns = ...",
        "",
        "ns.FontFamilies = {",
        "\tfamilies = {",
    ]
    for family in sorted(families):
        parts = []
        for alphabet in sorted(families[family]):
            file, height = families[family][alphabet]
            parts.append('%s = { "%s", %g }' % (alphabet, file.replace("\\", "\\\\"), height))
        lines.append('\t\t["%s"] = { %s },' % (family, ", ".join(parts)))
    lines += ["\t},", "\tinherits = {"]
    for name in sorted(inherits):
        lines.append('\t\t["%s"] = "%s",' % (name, inherits[name]))
    lines += ["\t},", "}", ""]
    with open(os.path.join(ROOT, "Data", "FontFamilies.lua"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("%d families, %d font objects that inherit one" % (len(families), len(inherits)))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/ForeverPlus-dev/wow-ui-source"))
