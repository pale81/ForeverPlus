-- Generates Data/Points.lua: flight points and instance entrances.
--
--   lua5.1 tools/build_points.lua <att checkout> <addon root> <client build> <TaxiNodes.csv> <Map.csv> <AreaTable.csv>
--
-- Flight points (taxi node, flight master, position, faction) come from the
-- Forever data of AllTheThings (MIT, https://github.com/ATTWoWAddon/AllTheThings;
-- names of the flight masters from the comments of its source tables, the
-- node names from the game table TaxiNodes). Instance entrances come from the
-- game table Map (the corpse position of an instance is its entrance) and,
-- for instances without one, from AllTheThings. The CSV files are the
-- downloads of wago.tools/db2 for the client build.
local att, root, build = assert(arg[1], "ATT checkout"), assert(arg[2], "addon root"), assert(arg[3], "client build")
local taxiCsv, mapCsv, areaCsv = assert(arg[4], "TaxiNodes.csv"), assert(arg[5], "Map.csv"), assert(arg[6], "AreaTable.csv")

local here = arg[0]:match("^(.*)/[^/]*$") or "."
local loader = dofile(here .. "/att_loader.lua")

---------------------------------------------------------------------------
-- CSV with quoted fields: rows by the column names of the first line
---------------------------------------------------------------------------
local function SplitLine(line)
	local fields, i = {}, 1
	while i <= #line + 1 do
		if line:sub(i, i) == '"' then
			local value, j = {}, i + 1
			while true do
				local quote = line:find('"', j, true)
				value[#value + 1] = line:sub(j, quote - 1)
				if line:sub(quote + 1, quote + 1) == '"' then
					value[#value + 1] = '"'
					j = quote + 2
				else
					i = quote + 2
					break
				end
			end
			fields[#fields + 1] = table.concat(value)
		else
			local comma = line:find(",", i, true) or #line + 1
			fields[#fields + 1] = line:sub(i, comma - 1)
			i = comma + 1
		end
	end
	return fields
end

local function Csv(path)
	local rows, header = {}, nil
	local pending
	for line in io.lines(path) do
		line = line:gsub("^\239\187\191", ""):gsub("\r$", "")
		-- A quoted field may contain line breaks.
		if pending then
			line = pending .. "\n" .. line
			pending = nil
		end
		local _, quotes = line:gsub('"', "")
		if quotes % 2 == 1 then
			pending = line
		elseif line ~= "" then
			local fields = SplitLine(line)
			if not header then
				header = fields
			else
				local row = {}
				for k, name in ipairs(header) do
					row[name] = fields[k]
				end
				rows[#rows + 1] = row
			end
		end
	end
	return rows
end

local function Number(value)
	return (("%.2f"):format(value):gsub("%.?0+$", ""))
end

local function Quote(s)
	return ("%q"):format(s):gsub("\\\n", "\\n")
end

---------------------------------------------------------------------------
-- AllTheThings: flight paths and instances
---------------------------------------------------------------------------
local flights, instances = {}, {}
local function Walk(node)
	if type(node) ~= "table" or type(node.t) ~= "table" then
		return
	end
	local t = node.t
	if node.kind == "CreateFlightPath" and type(t.coords) == "table" then
		flights[node.id] = t
	elseif node.kind == "CreateInstance" and t["zone-text-areaID"] then
		instances[#instances + 1] = t
	end
	for _, child in ipairs(loader.children(node)) do
		Walk(child)
	end
end
for _, root in ipairs(loader.load(att, { "Zones", "Instances" })) do
	Walk(root)
end

-- Names of the flight masters from the comments of the source tables.
local npcs, ids = {}, {}
for _, t in pairs(flights) do
	local npc = type(t.crs) == "table" and t.crs[1]
	if npc and not npcs[npc] then
		npcs[npc] = true
		ids[#ids + 1] = tostring(npc)
	end
end
local names = {}
local pipe = io.popen(("grep -rhoE '(\\[\"cr\"\\]|[^a-z]cr)[[:space:]]*=[[:space:]]*(%s),[[:space:]]*--.*' '%s/.contrib/.db/forever' '%s/.contrib/.db/standard'")
	:format(table.concat(ids, "|"), att, att))
for line in pipe:lines() do
	local npc, comment = line:match("=%s*(%d+),%s*%-%-%s*(.-)%s*$")
	npc = tonumber(npc)
	if npc and not names[npc] and comment ~= "" then
		names[npc] = comment
	end
end
pipe:close()

local nodeNames = {}
for _, row in ipairs(Csv(taxiCsv)) do
	nodeNames[tonumber(row.ID)] = row.Name_lang
end

---------------------------------------------------------------------------
-- Output
---------------------------------------------------------------------------
local out = {}
local function Add(line) out[#out + 1] = line end
Add("-- Generated by tools/build_points.lua; do not edit by hand.")
Add("-- Flight points: AllTheThings Forever data (MIT) with node names from the game table TaxiNodes.")
Add("-- Instance entrances: game table Map (corpse position) and AllTheThings (MIT).")
Add("-- flights[taxi node] = { node name, map, x, y, team (A, H, N), flight master, title or false, npc ID }")
Add("-- entrances[instance map] = { name, \"w\", continent, world x, world y } or { name, \"m\", map, x, y }")
Add("local _, ns = ...")
Add("")
Add("ns.Points = {")
Add(("\tbuild = %s,"):format(Quote(build)))
Add("\tflights = {")
local nodeIDs, count = {}, 0
for id in pairs(flights) do nodeIDs[#nodeIDs + 1] = id end
table.sort(nodeIDs)
for _, id in ipairs(nodeIDs) do
	local t = flights[id]
	local map = next(t.coords)
	local point = map and t.coords[map][1]
	local npc = type(t.crs) == "table" and t.crs[1]
	if nodeNames[id] and point and type(point[1]) == "number" and type(point[2]) == "number" and npc then
		local comment = names[npc]
		local name, title
		if comment then
			name, title = comment:match("^(.-)%s*<(.-)>%s*$")
			name = name or comment
		end
		local team = t.r == 1 and "H" or t.r == 2 and "A" or "N"
		Add(("\t\t[%d] = { %s, %d, %s, %s, %q, %s, %s, %d },"):format(id, Quote(nodeNames[id]), map, Number(point[1]), Number(point[2]),
			team, name and Quote(name) or "false", title and Quote(title) or "false", npc))
		count = count + 1
	end
end
Add("\t},")

-- Instance entrances
local areas = {}
for _, row in ipairs(Csv(areaCsv)) do
	areas[tonumber(row.ID)] = tonumber(row.ContinentID)
end
-- Only the instances of the group finder list (Data/Instances.lua) are shown.
local wanted = {}
assert(loadfile(root .. "/Data/Instances.lua"))("ForeverPlus", wanted)
wanted = wanted.Instances
local entrances = {}
for _, row in ipairs(Csv(mapCsv)) do
	local id, x, y = tonumber(row.ID), tonumber(row.Corpse_0), tonumber(row.Corpse_1)
	if wanted[id] and x and y and (x ~= 0 or y ~= 0) and tonumber(row.CorpseMapID) and tonumber(row.CorpseMapID) >= 0 then
		entrances[id] = ("{ %s, \"w\", %d, %s, %s }"):format(Quote(row.MapName_lang), tonumber(row.CorpseMapID), Number(x), Number(y))
	end
end
local mapNames = {}
for _, row in ipairs(Csv(mapCsv)) do
	mapNames[tonumber(row.ID)] = row.MapName_lang
end
local fromAtt = 0
for _, t in ipairs(instances) do
	local instance = areas[t["zone-text-areaID"]]
	local map = type(t.coords) == "table" and next(t.coords)
	local point = map and t.coords[map][1]
	if instance and wanted[instance] and not entrances[instance] and point and type(point[1]) == "number" and type(point[2]) == "number" then
		entrances[instance] = ("{ %s, \"m\", %d, %s, %s }"):format(Quote(mapNames[instance] or "?"), map, Number(point[1]), Number(point[2]))
		fromAtt = fromAtt + 1
	end
end
Add("\tentrances = {")
local instanceIDs = {}
for id in pairs(entrances) do instanceIDs[#instanceIDs + 1] = id end
table.sort(instanceIDs)
for _, id in ipairs(instanceIDs) do
	Add(("\t\t[%d] = %s,"):format(id, entrances[id]))
end
Add("\t},")
Add("}")
Add("")
local file = assert(io.open(root .. "/Data/Points.lua", "wb"))
file:write(table.concat(out, "\n"))
file:close()
print(("flights %d (of %d), entrances %d (%d from AllTheThings)"):format(count, #nodeIDs, #instanceIDs, fromAtt))
