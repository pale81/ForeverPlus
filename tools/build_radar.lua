-- Generates Data/Radar.lua (recipe vendors with positions and their recipes)
-- from the Forever data of AllTheThings (MIT, https://github.com/ATTWoWAddon/AllTheThings).
--
--   git clone --depth 1 https://github.com/ATTWoWAddon/AllTheThings att
--   lua5.1 tools/build_radar.lua <att checkout> <addon root> <client build>
--
-- Reads the generated db/Camelot/Categories (the compiled data of the Forever
-- build) and takes the names of the NPCs from the comments of the source
-- tables in .contrib/.db (the compiled data has none).
local att, root, build = assert(arg[1], "ATT checkout"), assert(arg[2], "addon root"), assert(arg[3], "client build")

local function Read(path)
	local file = assert(io.open(path, "rb"))
	local text = file:read("*a")
	file:close()
	return (text:gsub("^\239\187\191", ""))
end

---------------------------------------------------------------------------
-- Load the compiled categories with stand-ins for ATT's constructors
---------------------------------------------------------------------------
local function Node(kind)
	return function(id, t)
		return { kind = kind, id = id, t = type(t) == "table" and t or {} }
	end
end
local env = {}
for _, name in ipairs({ "CreateAchievement", "CreateHeader", "CreateAchievementCriteria", "CreateCurrencyClass",
	"CreateExploration", "CreateFaction", "CreateFilter", "CreateFlightPath", "CreateCustomHeader", "CreateItem",
	"CreateMap", "CreateMount", "CreateNPC", "CreateObject", "CreateSpecies", "CreateProfession", "CreateQuest",
	"CreateQuestObjective", "CreateRecipe", "CreateItemSource" }) do
	env[name] = Node(name)
end
local Any
Any = function()
	return setmetatable({}, { __call = function() return Any() end, __index = function() return Any() end, __newindex = function() end })
end
local handler
env.AddEventHandler = function(_, fn) handler = fn end
setmetatable(env, { __index = function() return Any() end })

local vendors = {} -- npc -> { coords, race, items = { itemID, … } }
local drops = {}   -- itemID -> { creature IDs }

local function Walk(node, npc)
	if type(node) ~= "table" or type(node.t) ~= "table" then
		return
	end
	local t = node.t
	if node.kind == "CreateNPC" then
		npc = nil
		if type(t.coords) == "table" then
			vendors[node.id] = vendors[node.id] or { coords = t.coords, race = t.r, items = {} }
			npc = vendors[node.id]
		end
	elseif node.kind == "CreateRecipe" and t.itemID then
		if npc then
			npc.items[#npc.items + 1] = t.itemID
		end
		if type(t.crs) == "table" then
			drops[t.itemID] = t.crs
		end
	end
	for _, child in ipairs(t.g or t) do
		Walk(child, npc)
	end
	if t.g then
		for _, child in ipairs(t) do
			Walk(child, npc)
		end
	end
end

for _, file in ipairs({ "Zones", "Instances", "Holidays", "WorldDrops", "PVP", "Professions" }) do
	local chunk = assert(loadstring(Read(att .. "/db/Camelot/Categories/" .. file .. ".lua"), file))
	local categories = {}
	chunk("ATT", env)
	handler(categories)
	for _, root in pairs(categories) do
		Walk(root)
	end
end

---------------------------------------------------------------------------
-- Names from the comments of the source tables
---------------------------------------------------------------------------
local wanted, ids = {}, {}
for npc, vendor in pairs(vendors) do
	if #vendor.items > 0 then
		wanted[npc] = true
		ids[#ids + 1] = tostring(npc)
	end
end
table.sort(ids, function(a, b) return tonumber(a) < tonumber(b) end)
local names = {}
local command = ("grep -rhoE 'n\\((%s),[[:space:]]*\\{[[:space:]]*--.*' '%s/.contrib/.db/forever' '%s/.contrib/.db/standard'")
	:format(table.concat(ids, "|"), att, att)
local pipe = io.popen(command)
for line in pipe:lines() do
	local npc, comment = line:match("^n%((%d+),[ \t]*{[ \t]*%-%-%s*(.-)%s*$")
	npc = tonumber(npc)
	if npc and not names[npc] and comment ~= "" then
		names[npc] = comment
	end
end
pipe:close()

---------------------------------------------------------------------------
-- Output
---------------------------------------------------------------------------
local function Number(value)
	return (("%.2f"):format(value):gsub("%.?0+$", ""))
end
local MAX_VENDOR_MAPS = 3 -- more maps: a summoned helper without a fixed place
local function Quote(s)
	return ("%q"):format(s):gsub("\\\n", "\\n")
end

local out = {}
local function Add(line) out[#out + 1] = line end
Add("-- Generated by tools/build_radar.lua from the Forever data of AllTheThings")
Add("-- (MIT, https://github.com/ATTWoWAddon/AllTheThings); do not edit by hand.")
Add("-- vendors[npc] = { name, title or false, team (A, H, N), { { map, x, y }, … }, { recipe item, … } }")
Add("-- drops[recipe item] = number of creatures that drop it (the profession comes from the item class)")
Add("local _, ns = ...")
Add("")
Add("ns.RadarData = {")
Add(("\tbuild = %s,"):format(Quote(build)))
Add(("\tsource = %s,"):format(Quote("AllTheThings Forever data (MIT)")))
Add("\tvendors = {")
local count, itemCount, unnamed = 0, 0, 0
local sorted = {}
for npc in pairs(wanted) do sorted[#sorted + 1] = npc end
table.sort(sorted)
for _, npc in ipairs(sorted) do
	local vendor = vendors[npc]
	local points, maps = {}, {}
	for map, list in pairs(vendor.coords) do
		maps[#maps + 1] = map
	end
	table.sort(maps)
	if #maps <= MAX_VENDOR_MAPS then
		for _, map in ipairs(maps) do
			local list = vendor.coords[map]
			for _, point in ipairs(list) do
				if type(point[1]) == "number" and type(point[2]) == "number" then
					points[#points + 1] = ("{ %d, %s, %s }"):format(map, Number(point[1]), Number(point[2]))
				end
			end
		end
	end
	if #points > 0 then
		local comment = names[npc]
		local name, title = "?", false
		if comment then
			name, title = comment:match("^(.-)%s*<(.-)>%s*$")
			name = name or comment
		else
			unnamed = unnamed + 1
		end
		local team = vendor.race == 1 and "H" or vendor.race == 2 and "A" or "N"
		table.sort(vendor.items)
		local items, last = {}, nil
		for _, item in ipairs(vendor.items) do
			if item ~= last then
				items[#items + 1] = tostring(item)
				itemCount = itemCount + 1
			end
			last = item
		end
		Add(("\t\t[%d] = { %s, %s, %q, { %s }, { %s } },"):format(npc, Quote(name), title and Quote(title) or "false", team,
			table.concat(points, ", "), table.concat(items, ", ")))
		count = count + 1
	end
end
Add("\t},")
Add("\tdrops = {")
local dropIDs = {}
for item in pairs(drops) do dropIDs[#dropIDs + 1] = item end
table.sort(dropIDs)
for _, item in ipairs(dropIDs) do
	Add(("\t\t[%d] = %d,"):format(item, #drops[item]))
end
Add("\t},")
Add("}")
Add("")

local file = assert(io.open(root .. "/Data/Radar.lua", "wb"))
file:write(table.concat(out, "\n"))
file:close()
print(("vendors %d, recipe rows %d, without name %d, drops %d"):format(count, itemCount, unnamed, #dropIDs))
