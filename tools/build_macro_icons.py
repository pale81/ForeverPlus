# Builds Data/MacroIcons.lua: a search text for every icon of the macro icon picker.
# Usage: python3 -I tools/build_macro_icons.py CSV_DIR BUILD
# CSV_DIR holds the wago.tools/db2 exports of the client build: ManifestInterfaceData.csv, SpellMisc.csv,
# Item.csv, SpellName_enUS.csv, SpellName_deDE.csv, ItemSparse_enUS.csv and ItemSparse_deDE.csv.
import collections
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCALES = ("enUS", "deDE")
NAMES_PER_LOCALE = 6  # most frequent names of the spells and items that use the icon
PLACEHOLDER_NAMES = 300  # icons with more distinct names are placeholders (TEMP, Trade_Engineering)
# Internal and test names: brackets, set bonus rows ("S03 - Item - ..."), ranks and numbers, old data.
JUNK = re.compile(r"[\[\]()]|\bdnt\b|\bdnd\b|deprecated|\bold\b|\btest|unused|\bqa\b| - |\d|zz|monster|npc|^\W", re.I)


def read_csv(path):
    with open(path, encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def clean(text):
    return " ".join(text.replace("|", " ").split()).lower()


def main(csv_dir, build):
    csv_dir = Path(csv_dir)
    icons = {
        int(row["ID"]): row["FileName"].rsplit(".", 1)[0]
        for row in read_csv(csv_dir / "ManifestInterfaceData.csv")
        if row["FilePath"].lower() == "interface\\icons\\"
    }
    spell_icons = {}
    for row in read_csv(csv_dir / "SpellMisc.csv"):
        icon = int(row["SpellIconFileDataID"])
        if icon in icons and (row["DifficultyID"] == "0" or row["SpellID"] not in spell_icons):
            spell_icons[row["SpellID"]] = icon
    item_icons = {row["ID"]: int(row["IconFileDataID"]) for row in read_csv(csv_dir / "Item.csv")
                  if int(row["IconFileDataID"]) in icons}

    counts = {locale: collections.defaultdict(collections.Counter) for locale in LOCALES}
    for locale in LOCALES:
        for table, column, owners in (("SpellName", "Name_lang", spell_icons), ("ItemSparse", "Display_lang", item_icons)):
            for row in read_csv(csv_dir / f"{table}_{locale}.csv"):
                icon, name = owners.get(row["ID"]), row[column].strip()
                if icon and name and not JUNK.search(name):
                    counts[locale][icon][clean(name)] += 1

    lines = []
    for icon in sorted(icons):
        parts = [clean(icons[icon].replace("_", " "))]
        for locale in LOCALES:
            names = counts[locale][icon]
            if len(names) <= PLACEHOLDER_NAMES:
                parts += [name for name, _ in sorted(names.items(), key=lambda kv: (-kv[1], len(kv[0]), kv[0]))[:NAMES_PER_LOCALE]]
        text = "|".join(dict.fromkeys(parts))
        assert "\t" not in text and "\n" not in text and "]==]" not in text
        lines.append(f"{text}\t{icon}")

    out = ROOT / "Data" / "MacroIcons.lua"
    out.write_text(
        "-- Generated by tools/build_macro_icons.py. See DATA-SOURCES.md.\n"
        f"-- Forever client tables, build {build}: icon file names (ManifestInterfaceData) and the English and\n"
        "-- German names of the spells (SpellMisc, SpellName) and items (Item, ItemSparse) that use each icon.\n"
        "-- One line per icon: search text, tab, file ID.\n"
        "local _, ns = ...\n\n"
        "ns.MacroIconNames = [==[\n" + "\n".join(lines) + "\n]==]\n",
        encoding="utf-8",
    )
    print(f"{len(lines)} icons, {sum(1 for line in lines if '|' in line)} with names, {out.stat().st_size} bytes")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__ or "Usage: python3 -I tools/build_macro_icons.py CSV_DIR BUILD")
    main(sys.argv[1], sys.argv[2])
