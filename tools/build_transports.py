#!/usr/bin/env python3
"""Builds Data/TransportPaths.lua: the stops of the ships and zeppelins from the game tables TaxiPath and
TaxiPathNode (CSV from wago.tools for the client build). A transport path is a taxi path whose nodes wait at a
stop (Delay > 0); its stops in path order form a loop (two stops: there and back).

Usage: python3 -I tools/build_transports.py <folder with TaxiPath.csv and TaxiPathNode.csv> BUILD
"""
import csv
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SAME_STOP = 30.0  # yards: stops this close are one (a path passing its first stop again)


def rows(folder, name):
    with open(os.path.join(folder, name + '.csv'), newline='', encoding='utf-8-sig') as f:
        return list(csv.DictReader(f))


def stops_of(nodes):
    """The waiting points of one path in order, without repeats."""
    stops = []
    for n in sorted(nodes, key=lambda n: int(n['NodeIndex'])):
        if int(n['Delay']) <= 0:
            continue
        stop = (int(n['ContinentID']), float(n['Loc_0']), float(n['Loc_1']))
        if any(s[0] == stop[0] and abs(s[1] - stop[1]) + abs(s[2] - stop[2]) < SAME_STOP for s in stops):
            continue
        stops.append(stop)
    return stops


def main(folder, build):
    nodes = defaultdict(list)
    for n in rows(folder, 'TaxiPathNode'):
        nodes[int(n['PathID'])].append(n)
    paths = []
    for path_id in sorted(nodes):
        stops = stops_of(nodes[path_id])
        if len(stops) >= 2:
            paths.append((path_id, stops))
    out = ['-- Generated by tools/build_transports.py from the game tables TaxiPath and TaxiPathNode, build %s.' % build,
           '-- Ships and zeppelins: per path its stops in order (a loop), each { continent, world x, world y }.',
           'local _, ns = ...', '', 'ns.TransportPaths = {']
    for path_id, stops in paths:
        text = ', '.join('{ %d, %.1f, %.1f }' % s for s in stops)
        out.append('\t{ %s }, -- path %d' % (text, path_id))
    out.append('}')
    path = os.path.join(ROOT, 'Data', 'TransportPaths.lua')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('%d paths written to %s' % (len(paths), path))


if __name__ == '__main__':
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
