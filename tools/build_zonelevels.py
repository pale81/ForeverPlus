# Builds Data/ZoneLevels.lua (the level range of each zone) from the open data of Efficient Games (CC BY 4.0,
# https://github.com/JIVESCORP/eg-link-output-wowf): the levels of the creatures players killed there. The game
# itself has no ranges for Forever's zones (C_Map.GetMapLevels gives 0), and the Classic ranges do not fit.
# Counted is every kind of creature once (not every kill: how often a place was played says nothing about its
# levels), only those no faction sees as friendly (no guards, no townsfolk), no elites. With 10 kinds or more the
# lowest and highest 5 % are left out (single strays); zones with fewer than 3 kinds get no range.
# Usage: python3 tools/build_zonelevels.py <checkout of eg-link-output-wowf>
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRODUCTS = ('wow_classic_beta', 'wowf')  # both are WoW Forever (the beta, then the live client)
FRIENDLY = 5  # reactions: 1-3 hostile, 4 neutral, 5 and up friendly
SKIP = {'elite', 'rareelite', 'worldboss'}
MIN_KINDS, TRIM_FROM, TRIM = 3, 10, 0.05


def read(checkout):
    kinds, builds = {}, []
    for product in PRODUCTS:
        base = os.path.join(checkout, 'data', product)
        for build in sorted(os.listdir(base)):
            path = os.path.join(base, build, 'creatures.json')
            if not os.path.exists(path):
                continue
            builds.append(build)
            with open(path, encoding='utf-8') as f:
                for npc, row in json.load(f).get('creatures', {}).items():
                    kind = kinds.setdefault(int(npc), {'levels': set(), 'maps': set(), 'classes': set(), 'friendly': False, 'reactions': False})
                    kind['levels'].update(int(level) for level in (row.get('levels') or {}) if str(level).isdigit() and int(level) > 0)
                    kind['classes'].update(row.get('classifications') or [])
                    for seen in (row.get('reactions') or {}).values():
                        for reaction in (seen if isinstance(seen, list) else [seen]):
                            kind['reactions'] = True
                            if isinstance(reaction, int) and reaction >= FRIENDLY:
                                kind['friendly'] = True
                    for position in row.get('positions') or []:
                        uimap = position[1] if isinstance(position, list) and len(position) > 1 else position.get('uiMap') if isinstance(position, dict) else None
                        if isinstance(uimap, int) and uimap > 0:
                            kind['maps'].add(uimap)
    return kinds, sorted(set(builds))


def ranges(kinds):
    per_map = {}
    for kind in kinds.values():
        if not kind['levels'] or not kind['reactions'] or kind['friendly'] or kind['classes'] & SKIP:
            continue
        for uimap in kind['maps']:
            per_map.setdefault(uimap, []).append((min(kind['levels']), max(kind['levels'])))
    result = {}
    for uimap, found in per_map.items():
        if len(found) < MIN_KINDS:
            continue
        lows, highs = sorted(f[0] for f in found), sorted(f[1] for f in found)
        cut = int(len(found) * TRIM) if len(found) >= TRIM_FROM else 0
        result[uimap] = (lows[cut], highs[len(highs) - 1 - cut])
    return result


def main(checkout):
    kinds, builds = read(checkout)
    result = ranges(kinds)
    out = ['-- Generated by tools/build_zonelevels.py from the open data of Efficient Games',
           '-- (https://github.com/JIVESCORP/eg-link-output-wowf, CC BY 4.0, builds %s to %s):' % (builds[0], builds[-1]),
           '-- the levels of the creatures players killed in a zone, every kind once (see the script).',
           '-- ZoneLevels[uiMapID] = { lowest, highest }',
           'local _, ns = ...', '', 'ns.ZoneLevels = {']
    for uimap in sorted(result):
        out.append('\t[%d] = { %d, %d },' % (uimap, result[uimap][0], result[uimap][1]))
    out.append('}')
    with open(os.path.join(ROOT, 'Data', 'ZoneLevels.lua'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print('%d zones' % len(result))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit('Usage: python3 tools/build_zonelevels.py <checkout of eg-link-output-wowf>')
    main(sys.argv[1])
