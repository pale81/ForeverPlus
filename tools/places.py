# Builds Data/Places.lua (towns and capital cities with their world position)
# from the game tables AreaPOI, AreaTable and UiMapAssignment as CSV, e.g. the
# "CSV" downloads on wago.tools/db2 for the client build. Towns are the points
# of interest flagged like Goldshire or Razor Hill, capitals like Stormwind;
# the area ID gives the name in the client's language at runtime, the parent
# areas the map the place belongs to.
# Usage: python3 tools/places.py AreaPOI.csv AreaTable.csv UiMapAssignment.csv BUILD
import csv, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOWN_FLAGS = (1, 5)
CAPITAL_FLAGS = 29


def rows(path):
    with open(path, newline='', encoding='utf-8-sig') as f:
        return list(csv.DictReader(f))


def area_index(areas):
    index = {}
    for a in areas:
        index.setdefault((a['AreaName_lang'].lower(), a['ContinentID']), int(a['ID']))
    return index


def find_area(index, name, continent):
    candidates = [name, name + ' City']
    if name.startswith('The '):
        candidates.append(name[4:])
    for candidate in candidates:
        area = index.get((candidate.lower(), continent))
        if area:
            return area
    return 0


def home_map(area, parents, maps):
    # The first area up the parent chain that has a map of its own.
    seen = set()
    while area and area not in seen:
        if area in maps:
            return maps[area]
        seen.add(area)
        area = parents.get(area, 0)
    return 0


def map_at(x, y, regions):
    # Places without a parent area: the zone map whose region holds the
    # position, the nearest region centre when several do.
    best = None
    for ui_map, (min_x, min_y, max_x, max_y) in regions.items():
        if min_x <= x <= max_x and min_y <= y <= max_y:
            distance = (x - (min_x + max_x) / 2) ** 2 + (y - (min_y + max_y) / 2) ** 2
            if best is None or distance < best[0]:
                best = (distance, ui_map)
    return best[1] if best else 0


def main(poi_path, area_path, assignment_path, build):
    areas = rows(area_path)
    index = area_index(areas)
    parents = {int(a['ID']): int(a['ParentAreaID']) for a in areas}
    maps, regions = {}, {}
    for a in sorted(rows(assignment_path), key=lambda a: int(a['OrderIndex'])):
        if int(a['AreaID']) > 0:
            maps.setdefault(int(a['AreaID']), int(a['UiMapID']))
            regions[(int(a['MapID']), int(a['UiMapID']))] = (float(a['Region_0']), float(a['Region_1']), float(a['Region_3']), float(a['Region_4']))
    places, unmatched = [], []
    for p in rows(poi_path):
        flags = int(p['Flags'])
        if int(p['PlayerConditionID']) != 0 or int(p['WorldStateID']) != 0:
            continue
        if flags == CAPITAL_FLAGS:
            kind = 'city'
        elif flags in TOWN_FLAGS and p['Icon'] in ('4', '6'):
            kind = 'town'
        else:
            continue
        area = find_area(index, p['Name_lang'], p['ContinentID'])
        home = home_map(area, parents, maps)
        if not home:
            continent = int(p['ContinentID'])
            home = map_at(float(p['Pos_0']), float(p['Pos_1']),
                          {ui: r for (c, ui), r in regions.items() if c == continent})
            print('%s: map %d by position' % (p['Name_lang'], home))
        if not area or not home:
            unmatched.append(p['Name_lang'])
        places.append((int(p['ContinentID']), float(p['Pos_0']), float(p['Pos_1']), area, p['Name_lang'], kind, home))

    out = ['-- Generated by tools/places.py from AreaPOI and AreaTable, build %s.' % build,
           '-- { continent, world x, world y, area ID (0: none), name, "city"|"town", map ID of the place (0: none) }',
           'local _, ns = ...', '',
           'ns.PlaceBuild = "%s"' % build,
           'ns.Places = {']
    for c, x, y, area, name, kind, home in places:
        out.append('\t{ %d, %.1f, %.1f, %d, "%s", "%s", %d },' % (c, x, y, area, name.replace('"', '\\"'), kind, home))
    out.append('}')
    with open(os.path.join(ROOT, 'Data', 'Places.lua'), 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('%d places (%d cities); without area or map: %s' % (len(places), sum(1 for p in places if p[5] == 'city'), unmatched or '-'))


if __name__ == '__main__':
    if len(sys.argv) != 5:
        sys.exit('Usage: python3 tools/places.py AreaPOI.csv AreaTable.csv UiMapAssignment.csv BUILD')
    main(*sys.argv[1:])
