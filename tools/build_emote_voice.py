#!/usr/bin/env python3
"""Build German male-dwarf emote data and optional speech clips.

Export EmotesText, EmotesTextSound and EmotesTextData (locale=deDE) for the
manifest's build from wago.tools/db2 into --tables. Pass Blizzard's
ChatEmoteConstants.lua with --constants. Add --reference and --model to render
speech with mlx-audio. Reference recordings and model caches stay outside the
addon. Requires ffmpeg for MP3 output and external Praat for optional prosody.
"""

import argparse
import csv
import json
from pathlib import Path
import re
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "tools" / "emote_voice_deDE.json"


def shape_prosody(audio, sample_rate, settings, praat="praat"):
    """Run the optional pitch-contour stage in a separate Praat process."""
    if not settings:
        return audio
    import numpy as np
    from scipy.io import wavfile

    spread = float(settings["pitch_spread"])
    limit = float(settings["max_shift_semitones"])
    if not np.isfinite([spread, limit]).all() or not 1 <= spread <= 1.25 or not 0 <= limit <= 1:
        raise ValueError("Prosody requires pitch_spread 1–1.25 and max_shift_semitones 0–1")
    if spread == 1 or limit == 0:
        return audio
    with tempfile.TemporaryDirectory(prefix="emote-prosody-") as folder:
        source, target = Path(folder) / "input.wav", Path(folder) / "output.wav"
        wavfile.write(source, sample_rate, audio.astype(np.float32))
        process = subprocess.run([
            str(praat), "--no-pref-files", "--no-plugins", "--FULL-TRUST", "--run", str(ROOT / "tools/process_emote_prosody.praat"),
            str(source), str(target), str(spread), str(limit),
        ], capture_output=True, text=True)
        if process.returncode or process.stderr.strip():
            raise RuntimeError(process.stderr.strip() or "Praat prosody processing failed")
        if process.stdout.strip() == "unchanged":
            return audio
        rate, result = wavfile.read(target)
    if rate != sample_rate or len(result) != len(audio) or not np.isfinite(result).all():
        raise ValueError("Invalid prosody resynthesis")
    if np.issubdtype(result.dtype, np.signedinteger):
        result = result.astype(np.float32) / (np.iinfo(result.dtype).max + 1)
    return result.astype(np.float32)


def read_table(folder, name):
    with (folder / (name + ".csv")).open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def build_data(manifest, tables, constants):
    tokens = set(re.findall(r'EMOTE\d+_TOKEN\s*=\s*"([^"]+)"', constants.read_text()))
    voiced = {
        int(row["EmotesTextID"])
        for row in read_table(tables, "EmotesTextSound")
        if int(row["RaceID"]) in (0, manifest["race_id"])
        and int(row["SexID"]) in (-1, manifest["sex_id"])
        and int(row["ClassID"]) == 0
        and int(row["SoundID"]) > 0
    }
    emotes = [
        row for row in read_table(tables, "EmotesText")
        if row["Name"] in tokens and int(row["ID"]) not in voiced
    ]
    selected = {row["Name"] for row in emotes}
    if selected != set(manifest["lines"]):
        raise ValueError(f"Missing lines: {selected - set(manifest['lines'])}; "
                         f"unexpected lines: {set(manifest['lines']) - selected}")
    formats = {}
    for row in read_table(tables, "EmotesTextData-deDE"):
        if int(row["RelationshipFlags"]) in (2, 6) and row["Text_lang"]:
            formats.setdefault(int(row["EmotesTextID"]), []).append(row["Text_lang"])
    output = [
        "-- Generated by tools/build_emote_voice.py from the Forever client tables.",
        f"-- Build {manifest['build']}, deDE, race 3, sex 0 (male).",
        "-- Emotes with an existing native voice are excluded.",
        "local _, ns = ...",
        "",
        "ns.EmoteVoiceData = {",
    ]
    for row in emotes:
        text_formats = list(dict.fromkeys(formats.get(int(row["ID"]), [])))
        if not text_formats and row["Name"] not in {"SIT", "STAND"}:
            raise ValueError(f"No German self-emote text for {row['Name']}")
        values = [row["Name"], *text_formats]
        output.append("\t{ " + ", ".join(json.dumps(value, ensure_ascii=False)
                                         for value in values) + " },")
    output.extend(["}", ""])
    (ROOT / "Data" / "EmoteVoice.lua").write_text("\n".join(output), encoding="utf-8")
    print(f"{len(emotes)} silent emotes, {len(voiced)} native voiced IDs excluded", flush=True)


def render(manifest, args):
    import mlx.core as mx
    import numpy as np
    from mlx_audio.audio_io import write
    from mlx_audio.tts.utils import load_model

    model = load_model(str(args.model))
    destination = ROOT / "Media" / "EmoteVoice" / "deDE" / "DwarfMale"
    destination.mkdir(parents=True, exist_ok=True)
    voice_filter = manifest.get("voice_filter", "anull")
    selected = [token for token in manifest["lines"]
                if not args.only or token in args.only]
    pending = [token for token in selected if args.overwrite or not (destination / f"{token}.mp3").exists()]
    with tempfile.TemporaryDirectory(prefix=".render-", dir=destination) as folder:
        source = Path(folder) / "speech.wav"
        encoded = Path(folder) / "speech.mp3"
        for offset in range(0, len(pending), args.batch_size):
            batch = pending[offset:offset + args.batch_size]
            mx.random.seed(manifest["seed"] + offset)
            # 12 seconds exceeds the 140-token limit at 12.5 frames/second.
            # Return one complete target-only chunk without decoding the reference again.
            results = model.batch_generate(
                texts=[manifest["lines"][token] for token in batch],
                ref_audio=str(args.reference), ref_text=manifest["reference_text"],
                lang_code="German", max_tokens=140, temperature=manifest.get("temperature", 0.7),
                repetition_penalty=1.05, verbose=False, stream=True, streaming_interval=12.0,
            )
            for result in results:
                token = batch[result.sequence_idx]
                if result.token_count >= 140:
                    raise ValueError(f"Speech reached its token limit: {token}")
                audio = np.asarray(result.audio)
                if not np.isfinite(audio).all() or not 0.25 < len(audio) / result.sample_rate < 10:
                    raise ValueError(f"Invalid speech audio: {token}")
                audio = shape_prosody(audio, result.sample_rate, manifest.get("prosody"), args.praat)
                write(str(source), audio, result.sample_rate)
                target = destination / f"{token}.mp3"
                # Trim only leading/trailing silence. Interior speech pauses remain.
                filters = (
                    "silenceremove=start_periods=1:start_duration=0.015:start_threshold=-45dB,"
                    "areverse,silenceremove=start_periods=1:start_duration=0.015:start_threshold=-45dB,"
                    f"areverse,highpass=f=60,{voice_filter},loudnorm=I=-20:TP=-2:LRA=7,"
                    "afade=t=in:d=0.005,apad=pad_dur=0.08"
                )
                subprocess.run([
                    "ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-i", str(source),
                    "-af", filters, "-ac", "1", "-ar", "24000", "-c:a", "libmp3lame",
                    "-q:a", "3", str(encoded),
                ], check=True)
                encoded.replace(target)
                print(f"{offset + result.sequence_idx + 1}/{len(pending)} {token} "
                      f"{len(audio) / result.sample_rate:.2f}s", flush=True)
            mx.clear_cache()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tables", type=Path)
    parser.add_argument("--constants", type=Path)
    parser.add_argument("--reference", type=Path)
    parser.add_argument("--model", type=Path)
    parser.add_argument("--praat", default="praat", help="external Praat executable for optional prosody")
    parser.add_argument("--batch-size", type=int, default=4)
    parser.add_argument("--only", nargs="+")
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()
    if bool(args.tables) != bool(args.constants):
        parser.error("--tables and --constants must be supplied together")
    if bool(args.reference) != bool(args.model):
        parser.error("--reference and --model must be supplied together")
    if not args.tables and not args.reference:
        parser.error("supply --tables/--constants, --reference/--model, or both")
    if args.batch_size < 1:
        parser.error("--batch-size must be positive")
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if args.only and not set(args.only) <= manifest["lines"].keys():
        parser.error("--only contains an unknown emote token")
    if args.tables:
        build_data(manifest, args.tables, args.constants)
    if args.reference:
        render(manifest, args)


if __name__ == "__main__":
    main()
