#!/usr/bin/env python3
"""Build the Emitter sound catalog from a wowdev community-listfile.csv."""

import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("listfile", type=Path)
    args = parser.parse_args()

    files = {}
    with args.listfile.open(encoding="utf-8-sig") as source:
        for line in source:
            file_id, _, path = line.rstrip().partition(";")
            path = path.lower()
            if path.startswith("sound/emitters/") and path.endswith((".ogg", ".mp3", ".wav")):
                files[int(file_id)] = path.removeprefix("sound/emitters/")
    if not files:
        parser.error("No files under sound/emitters/ in this listfile")

    output = Path(__file__).resolve().parents[1] / "Data" / "EmitterSounds.lua"
    with output.open("w", encoding="utf-8", newline="\n") as target:
        target.write("-- Generated by tools/build_emitter_sounds.py from the wowdev community listfile.\n")
        target.write("local _, ns = ...\nns.EmitterSounds = {\n")
        for file_id, path in sorted(files.items(), key=lambda item: (item[1], item[0])):
            target.write(f"\t{{ {file_id}, {json.dumps(path, ensure_ascii=False)} }},\n")
        target.write("}\n")


if __name__ == "__main__":
    main()
