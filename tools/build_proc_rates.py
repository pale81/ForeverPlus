# Usage: python3 -I tools/build_proc_rates.py WEAPON_PROCS_GO COMMIT
# WEAPON_PROCS_GO is tools/database/overrides/weapon_procs.go of WoWSims Forever (MIT) at COMMIT.
import re
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Source kinds: 1 measured on Forever (docs/evidence), 2 fitted from logs, 3 carried over from Classic or TBC.
KINDS = {"observed": 2, "vanilla-carryover": 3, "tbc-carryover": 3}


def read_rows(path):
    text = "\n".join(line for line in Path(path).read_text(encoding="utf-8").splitlines()
                     if not line.strip().startswith("//"))
    rows = {}
    for block in re.findall(r"\{([^{}]*ItemID:[^{}]*)\}", text):
        item = int(re.search(r"ItemID:\s*(\d+)", block).group(1))
        ppm = float(re.search(r"PPM:\s*([\d.]+)", block).group(1))
        source = re.search(r'Source:\s*"([^"]*)"', block).group(1)
        kind = 1 if source.startswith("EV-") else KINDS[source]
        if item in rows and rows[item] != (ppm, kind):
            raise SystemExit(f"item {item} has two rates")
        rows[item] = (ppm, kind)
    return rows


def main(path, commit):
    rows = read_rows(path)
    measured = [ppm for ppm, kind in rows.values() if kind == 1]
    default = round(statistics.median(measured), 2)
    lines = [
        "-- Generated by tools/build_proc_rates.py. See DATA-SOURCES.md.",
        f"-- WoWSims Forever weapon proc rates (MIT, commit {commit[:12]}): procs per minute of chance-on-hit weapons.",
        "-- Kind: 1 measured on Forever, 2 fitted from logs, 3 carried over from Classic or TBC.",
        "local _, ns = ...",
        f"ns.ProcRateDefault = {default:g} -- median of the {len(measured)} rates measured on Forever",
        "ns.ProcRates = {",
    ]
    for item in sorted(rows):
        ppm, kind = rows[item]
        lines.append(f"\t[{item}] = {{ {ppm:g}, {kind} }},")
    lines.append("}")
    (ROOT / "Data" / "ProcRates.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} weapons, default {default:g}")


if __name__ == "__main__":
    main(*sys.argv[1:])
