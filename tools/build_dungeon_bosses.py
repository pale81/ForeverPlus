"""Build boss pins from matching Blizzard map art and merge researched encounter details.

Usage: python3 tools/build_dungeon_bosses.py MOP_CSV_DIR RETAIL_CSV_DIR FOREVER_SPELL_NAME_CSV
Each journal directory needs JournalInstance, JournalEncounter, JournalEncounterXMapLoc,
UiMapXMapArt and UiMapArtTile as CSV. See DATA-SOURCES.md for the pinned builds.
"""

import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def rows(path):
    with path.open(newline="", encoding="utf-8-sig") as file:
        yield from csv.DictReader(file)


def journal_entries():
    """Read the fixed table layout emitted by build_dungeon_journal.py."""
    journal = (ROOT / "Data" / "DungeonJournal.lua").read_text()
    for match in re.finditer(r'^\t\t\[(\d+)\] = \{.*?^\t\t\},', journal, re.M | re.S):
        instance = match[0]
        floors = re.search(r'^\t\t\tfloors = (.+),$', instance, re.M)
        floors = [tuple(map(int, floor.split(", ")))
                  for floor in re.findall(r'\{ ([\d, ]+) \}', floors[1])] if floors else []
        panes = re.search(r'^\t\t\tminimap = (.+),$', instance, re.M)
        section_tiles = re.findall(r'\{ \d+, \d+, \{ \{ (\d+),', panes[1]) if panes else []
        names = dict((int(encounter), json.loads(name)) for encounter, name in
                     re.findall(r'^\t{4}\{ (\d+), ("(?:[^"\\]|\\.)*")', instance.split("\n\t\t\tquests =")[0], re.M))
        yield int(match[1]), floors, set(map(int, section_tiles)), names


def positions(folder, entries):
    instances = {int(row["ID"]): int(row["MapID"]) for row in rows(folder / "JournalInstance.csv")}
    tiles = defaultdict(dict)
    for row in rows(folder / "UiMapArtTile.csv"):
        if row["LayerIndex"] == "0":
            tiles[row["UiMapArtID"]][int(row["RowIndex"]), int(row["ColIndex"])] = int(row["FileDataID"])
    ui_maps = {
        row["UiMapID"]: tuple(file for _, file in sorted(tiles[row["UiMapArtID"]].items()))
        for row in rows(folder / "UiMapXMapArt.csv") if row["PhaseID"] == "0"
    }
    map_locations = defaultdict(list)
    for row in rows(folder / "JournalEncounterXMapLoc.csv"):
        if row["MapDisplayConditionID"] == "0":
            map_locations[row["JournalEncounterID"]].append(row)

    for row in rows(folder / "JournalEncounter.csv"):
        map_id = instances.get(int(row["JournalInstanceID"]))
        if map_id not in entries:
            continue
        floors, _, bosses = entries[map_id]
        # Some journal encounters have difficulty-specific IDs. Require a
        # matching instance and name before using their map position.
        encounter_id = next((key for key, name in bosses.items()
                             if name.casefold() == row["Name_lang"].casefold()), None)
        if encounter_id is None:
            continue
        points = []
        for point in map_locations[row["ID"]] or [row]:
            art = ui_maps.get(point["UiMapID"])
            x, y = float(point["Map_0"]), float(point["Map_1"])
            if art in floors and 0 < x < 1 and 0 < y < 1:
                points.append([art[0], round(x, 4), round(y, 4)])
        if points:
            yield encounter_id, {"position": points[0], "classic": True}


def lua_list(values):
    return "{ " + ", ".join(json.dumps(value, ensure_ascii=False) for value in values) + " }"


def build(mop, retail, spell_file):
    entries = {map_id: (floors, panes, bosses) for map_id, floors, panes, bosses in journal_entries()}
    found = dict(positions(retail, entries))
    found.update(positions(mop, entries))
    curated = json.loads((ROOT / "tools" / "dungeon_bosses.json").read_text())
    spell_ids = {int(row["ID"]) for row in rows(spell_file)}
    output = ["-- Generated by tools/build_dungeon_bosses.py. See DATA-SOURCES.md.",
              "-- Positions are { first tile FileDataID, horizontal fraction, vertical fraction }.",
              "local _, ns = ...", "", "ns.DungeonJournalBosses = {"]
    for floors, panes, bosses in entries.values():
        valid_tiles = panes | {floor[0] for floor in floors}
        for encounter_id, name in bosses.items():
            custom = curated.pop(str(encounter_id), {})
            info = {**found.get(encounter_id, {}), **custom}
            position = info.get("position")
            spells = info.get("spells", [])
            note = info.get("note")
            if position and (position[0] not in valid_tiles or not all(0 < v < 1 for v in position[1:])):
                raise ValueError(f"Unusable map position for {name}: {position}")
            if missing := set(spells) - spell_ids:
                raise ValueError(f"Spells absent from Forever for {name}: {missing}")
            fields = [f"{key} = {lua_list(info[key])}" for key in ("position", "spells", "note") if info.get(key)]
            if info.get("classic"):
                fields.append("classic = true")
            if info.get("approximate"):
                fields.append("approximate = true")
            if fields:
                output.append(f"\t[{encounter_id}] = {{ " + ", ".join(fields) + " },")
    if curated:
        raise ValueError(f"Unknown Forever encounter IDs: {', '.join(curated)}")
    output.extend(["}", ""])
    (ROOT / "Data" / "DungeonJournalBosses.lua").write_text("\n".join(output), encoding="utf-8")


if __name__ == "__main__":
    build(*map(Path, sys.argv[1:]))
