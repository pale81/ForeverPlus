#!/usr/bin/env python3
"""Builds Data/TransportPaths.lua from TaxiPathNode and UiMapAssignment CSVs.
Waiting points (Delay > 0) give the stops in order. UiMapAssignment places
them on the zone and overview maps.

Usage: python3 -I tools/build_transports.py <CSV folder> BUILD [UiMapAssignment.csv [map build]]
"""
import csv
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SAME_STOP = 30.0  # yards: stops this close are one (a path passing its first stop again)

# Path ID: vehicle and (zone map, area name ID, overview map, optional city/surrounding map) per stop.
# Path 295 is the old Menethil–Auberdine path. Its stops are now on the loop 11167.
ROUTES = {
    241: ('ship', [(1413, 392, 1414), (1434, 35, 1415)]),
    285: ('zeppelin', [(1434, 117, 1415), (1411, 1637, 1414, 1454)]),
    292: ('ship', [(1437, 150, 1415), (1445, 513, 1414)]),
    293: ('ship', [(1438, 702, 1414), (1439, 442, 1414)]),
    301: ('zeppelin', [(1434, 117, 1415), (1420, 1497, 1415)]),
    302: ('zeppelin', [(1411, 1637, 1414), (1420, 1497, 1415)]),
    303: ('ship', [(1444, 1116, 1414), (1444, 1108, 1414)]),
    11167: ('ship', [(1437, 150, 1415), (1424, 271, 1415), (1439, 442, 1414)]),
    11391: ('ship', [(1446, 977, 1414), (2548, 16727, 1415)]),
    11398: ('airship', [(1416, 279, 1415), (2521, 16628, 947)]),
    11457: ('zeppelin', [(1412, 17045, 1414), (2521, 16628, 947)]),
    11616: ('ship', [(1439, 442, 1414), (1453, 17203, 1415, 1429)]),
}


def rows(folder, name):
    with open(os.path.join(folder, name + '.csv'), newline='', encoding='utf-8-sig') as f:
        return list(csv.DictReader(f))


def stops_of(nodes):
    """The waiting points of one path in order, without repeats."""
    stops = []
    for n in sorted(nodes, key=lambda n: int(n['NodeIndex'])):
        if int(n['Delay']) <= 0:
            continue
        stop = (int(n['ContinentID']), float(n['Loc_0']), float(n['Loc_1']))
        if any(s[0] == stop[0] and abs(s[1] - stop[1]) + abs(s[2] - stop[2]) < SAME_STOP for s in stops):
            continue
        stops.append(stop)
    return stops


def map_position(assignments, map_id, stop):
    world_map, x, y = stop
    for row in assignments.get((map_id, world_map), []):
        min_x, min_y, max_x, max_y = (float(row[f'Region_{i}']) for i in (0, 1, 3, 4))
        if min_x <= x <= max_x and min_y <= y <= max_y:
            left, top, right, bottom = (float(row[k]) for k in ('UiMin_0', 'UiMin_1', 'UiMax_0', 'UiMax_1'))
            return left + (right - left) * (max_y - y) / (max_y - min_y), top + (bottom - top) * (max_x - x) / (max_x - min_x)


def main(folder, build, assignment_file=None, map_build=None):
    nodes = defaultdict(list)
    for n in rows(folder, 'TaxiPathNode'):
        nodes[int(n['PathID'])].append(n)
    assignments = defaultdict(list)
    with open(assignment_file or os.path.join(folder, 'UiMapAssignment.csv'), newline='', encoding='utf-8-sig') as f:
        for row in sorted(csv.DictReader(f), key=lambda row: int(row['OrderIndex'])):
            assignments[int(row['UiMapID']), int(row['MapID'])].append(row)

    out = [f'-- Generated by tools/build_transports.py from TaxiPathNode ({build}) and UiMapAssignment ({map_build or build}).',
           '-- { kind, stops in loop order }, each stop is { area ID, { map ID, x, y }, ... }.',
           '-- The first map is the zone or city. The other maps show the same stop.',
           'local _, ns = ...', '', 'ns.TransportPaths = {']
    for path_id, (kind, maps) in ROUTES.items():
        stops = stops_of(nodes[path_id])
        if len(stops) != len(maps):
            raise ValueError(f'Path {path_id}: expected {len(maps)} stops, found {len(stops)}')
        out.append(f'\t{{ "{kind}", {{ -- path {path_id}')
        for stop, (zone, area, overview, *extra) in zip(stops, maps):
            positions = []
            for map_id in dict.fromkeys([zone, *extra, overview, 947]):
                position = map_position(assignments, map_id, stop)
                if position is None:
                    if map_id == zone:
                        raise ValueError(f'Path {path_id}: stop {stop} lies outside map {zone}')
                    continue
                positions.append('{ %d, %.5f, %.5f }' % (map_id, *position))
            out.append('\t\t{ %d, %s },' % (area, ', '.join(positions)))
        out.append('\t} },')
    out.append('}')
    path = os.path.join(ROOT, 'Data', 'TransportPaths.lua')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('%d paths written to %s' % (len(ROUTES), path))


if __name__ == '__main__':
    if not 3 <= len(sys.argv) <= 5:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
