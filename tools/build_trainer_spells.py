# Usage: python3 -I tools/build_trainer_spells.py TRAINERS_JSON SKILL_LINE_ABILITY_CSV SPELL_LEVELS_CSV
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHAMAN_TRAINER = "3344"  # Kardris Dreamseeker, full shaman trainer in Orgrimmar
SHAMAN_SKILL_LINES = {373, 374, 375}
# Mail is a general proficiency. The trainer's Ghost Wolf has no skill-line row of its own.
EXTRA_SKILL_LINES = {8737: 0, 1238640: 373}


def read_csv(path):
    with open(path, encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def main(trainers_path, skills_path, levels_path):
    trainers = json.loads(Path(trainers_path).read_text(encoding="utf-8"))
    trainer = trainers["trainers"][SHAMAN_TRAINER]
    levels = {
        int(row["SpellID"]): int(row["SpellLevel"])
        for row in read_csv(levels_path)
        if row["DifficultyID"] == "0"
    }
    skill_lines = {
        int(row["Spell"]): int(row["SkillLine"])
        for row in read_csv(skills_path)
        if int(row["SkillLine"]) in SHAMAN_SKILL_LINES and int(row["ClassMask"]) & 64
    }
    skill_lines.update(EXTRA_SKILL_LINES)
    entries = []
    for spell in trainer["services"].values():
        spell_id = spell["spellId"]
        # The trainer records level 0 for spells already learned by the recorder.
        level = spell["level"] or levels[spell_id]
        if not 1 <= level <= 60:
            raise ValueError(f"Unexpected level {level} for spell {spell_id}")
        rank_text = spell.get("rankText") or ""
        rank = int(rank_text.removeprefix("Rank ")) if rank_text.startswith("Rank ") else None
        entries.append((skill_lines[spell_id], level, spell_id, rank))
    if len(entries) < 100:
        raise ValueError("The trainer record is incomplete")

    build = trainers["meta"]["clientBuild"]
    lines = [
        "-- Generated by tools/build_trainer_spells.py. See DATA-SOURCES.md.",
        f"-- Efficient Games trainer records (CC BY 4.0) and Forever client tables, build {build}.",
        "-- Entries contain spell ID, trainer level, skill line ID (0 for General) and optional rank.",
        "local _, ns = ...",
        "",
        "ns.TrainerSpells = {",
        "\tSHAMAN = {",
    ]
    for skill_line, level, spell_id, rank in sorted(entries):
        fields = (spell_id, level, skill_line) if rank is None else (spell_id, level, skill_line, rank)
        lines.append("\t\t{ " + ", ".join(map(str, fields)) + " },")
    lines.extend(("\t},", "}", ""))
    (ROOT / "Data" / "TrainerSpells.lua").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main(*sys.argv[1:])
